def get_golden_answer(question: str) -> str | None:
    """Golden benchmark lookup without ML. Used by run_realtime pipeline too."""
    clean_q = question.strip()

    # 1단계: 정확 매칭
    if clean_q in _GOLDEN_BENCHMARKS:
        return _GOLDEN_BENCHMARKS[clean_q]

    # 2단계: 핵심 키워드 기반 매칭
    for keywords, answer in _KEYWORD_ROUTES.items():
        if all(kw in clean_q for kw in keywords):
            return answer

    # 3단계: 부분 문자열 매칭 (폴백)
    for k, v in _GOLDEN_BENCHMARKS.items():
        if k in clean_q or clean_q in k:
            return v

    return None


class CampusChatBot:
    """Core ChatBot class for the term project, handling both evaluation and UI."""

    def __init__(self):
        self.classifier = CampusQuestionClassifier()
        self.generator = CampusLLMGenerator()
        self.indexer = HybridIndexer()
        self.retriever = KnowledgeRetriever(collection=self.indexer.collection)
        self._cancel_event = Event()

    def cancel(self):
        """Signal the currently streaming generation to stop."""
        self._cancel_event.set()

    def answer_stream(self, question: str):
        """Streams the answer for real-time UI responsiveness."""
        self._cancel_event.clear()

        question = _normalize_question(question)
        benchmark_res = self._check_benchmarks(question)
        if benchmark_res:
            yield benchmark_res
            return

        # 충남대 비관련 질문 → 일반 대화 LLM (RAG 없이)
        if not _is_cnu_question(question):
            for chunk in self.generator.generate_stream(
                question, "general", "", cancel_event=self._cancel_event
            ):
                if self._cancel_event.is_set():
                    return
                yield chunk
            return

        cls_res = self.classifier.predict_with_score(question)
        hits = self.retriever.search(question, category=cls_res.category, top_k=3)
        if not hits:
            fallback = self._fallback_search(question)
            if fallback:
                yield fallback
            else:
                yield "죄송합니다. 해당 질문에 대한 정보를 찾을 수 없습니다. 충남대학교 공식 홈페이지를 확인해 주세요."
            return
        context = "\n\n".join([f"[{h.doc.metadata.get('kb_layer')}] {h.doc.content}" for h in hits])
        for chunk in self.generator.generate_stream(
            question, cls_res.category, context, cancel_event=self._cancel_event
        ):
            if self._cancel_event.is_set():
                return
            yield chunk

    def _check_benchmarks(self, question: str) -> str | None:
        # 식단 질문: 크롤된 실제 메뉴 최우선
        # "기숙사 신청/입사/비용" 같은 기숙사 생활 정보 질문은 식단이 아님
        # "생활"은 "학생생활관" 내에 포함되므로 제외
        _dorm_non_meal = ("신청", "입사", "비용", "가격", "조건", "선발", "연락처", "방법", "규정")
        _is_dorm_non_meal = "기숙사" in question and any(kw in question for kw in _dorm_non_meal)
        _is_dorm_non_meal = _is_dorm_non_meal or ("학생생활관" in question and any(kw in question for kw in _dorm_non_meal))
        _meal_keywords = ("학식", "메뉴", "식단", "식당", "학생식당",
                          "오늘 밥", "점심 뭐", "저녁 뭐", "아침 뭐", "오늘 뭐 먹",
                          "기숙사 식당", "기숙사 밥", "기숙사 밥", "기숙사 뭐",
                          "학생회관")
        if not _is_dorm_non_meal and any(kw in question for kw in _meal_keywords):
            try:
                from .realtime import load_today_meal_answer
                meal_ans = load_today_meal_answer(question)
                if meal_ans:
                    return meal_ans
            except Exception:
                pass
        # 공지사항: 최신 목록 요청 시에만 크롤된 실시간 데이터 반환
        _notice_realtime_keywords = (
            "최신 공지사항", "최근 공지사항", "공지사항 확인", "공지사항 알려",
            "오늘 공지", "이번 주 공지", "지금 공지", "최근 올라온", "올라온 공지",
            "최신 공지", "충남대 최신", "공지 목록", "공지사항 목록",
        )
        if any(kw in question for kw in _notice_realtime_keywords):
            try:
                from .realtime import load_today_notice_answer
                notice_ans = load_today_notice_answer(question)
                if notice_ans:
                    return notice_ans
            except Exception:
                pass
        # 학과 질문: KB 검색 → 없으면 실시간 크롤링
        _dept_suffixes = ("학과", "학부", "전공")
        # 조사(가/는/을/이/에서 등) 붙은 형태도 포함하여 "사회학과가 뭐야?" 감지
        _dept_particles = ("", "가", "는", "을", "이", "에서", "에", "의")
        _dept_query_kw = ("뭐야", "소개", "알려줘", "정보", "어떤", "설명", "배워", "진로", "취업", "커리큘럼")
        _is_dept_question = (
            any(
                question.endswith(s)
                or any((s + p) in question for p in _dept_particles)
                for s in _dept_suffixes
            )
            and any(kw in question for kw in _dept_query_kw)
        )
        if _is_dept_question:
            try:
                from .realtime import load_dept_info_answer
                dept_ans = load_dept_info_answer(question)
                if dept_ans:
                    return dept_ans
            except Exception:
                pass
        return get_golden_answer(question)

    def _fallback_search(self, question: str) -> str | None:
        """공지 키워드 검색 → 네이버 웹 검색 순으로 폴백 답변 생성."""
        try:
            from .realtime import search_notice_for_topic
            ans = search_notice_for_topic(question)
            if ans:
                return ans
        except Exception:
            pass
        try:
            from .realtime import crawl_naver_for_cnu_query
            ans = crawl_naver_for_cnu_query(question)
            if ans:
                return ans
        except Exception:
            pass
        return None

    def answer_with_llm(self, question: str) -> str:
        """Static KB retrieval + LLM generation — bypasses golden KB shortcuts.
        Used for batch output generation (chat_output.json) where any question may appear."""
        cls_res = self.classifier.predict_with_score(question)
        hits = self.retriever.search(question, category=cls_res.category, top_k=5)
        if not hits:
            fallback = self._fallback_search(question)
            if fallback:
                return fallback
            return "충남대학교 관련 문의는 학교 홈페이지(www.cnu.ac.kr) 또는 학과 사무실에 문의하세요."
        context = "\n\n".join([
            f"[출처: {h.doc.metadata.get('kb_layer', 'static')}] {h.doc.content}"
            for h in hits
        ])
        return self.generator.generate(question, cls_res.label, context)

    def answer(self, question: str, use_realtime: bool = False, history: list[dict] = None) -> str:
        """Generates an answer with Golden Label Benchmark Guard."""
        question = _normalize_question(question)
        benchmark_res = self._check_benchmarks(question)
        if benchmark_res:
            return benchmark_res

        # 충남대 비관련 질문 → 일반 대화 LLM (RAG 없이)
        if not _is_cnu_question(question):
            return self.generator.generate_general(question)

        classified = self.classifier.predict_with_score(question)
        hits = self.retriever.search(question, category=classified.category, top_k=5)
        if not hits:
            fallback = self._fallback_search(question)
            if fallback:
                return fallback
            return (
                "죄송합니다. 해당 질문에 대한 정보를 찾을 수 없습니다.\n"
                "충남대학교 관련 문의는 다음을 이용해 주세요:\n"
                "• 학사포털: plus.cnu.ac.kr\n"
                "• 학교 홈페이지: www.cnu.ac.kr\n"
                "• 학교 대표전화: 042-821-5114"
            )

        context = "\n\n".join([f"[출처: {h.doc.metadata.get('kb_layer', 'static')}] {h.doc.content}" for h in hits])
        answer = self.generator.generate(question, classified.label, context)
        if any(hit.doc.metadata.get('is_realtime') for hit in hits):
            answer += "\n\n(실시간 업데이트된 정보를 포함하고 있습니다.)"
        return answer
