def _is_cnu_question(question: str) -> bool:
    """질문이 충남대학교 관련인지 판별한다."""
    q_lower = question.lower()
    return any(kw in q_lower for kw in _CNU_KEYWORDS)


def _normalize_question(question: str) -> str:
    """줄임말·속어를 공식 표현으로 변환한다."""
    q = question.strip()

    # 1단계: regex 기반 패턴 (순서 중요 — regex 먼저)
    # "N학생회관" → "제N학생회관" (제 없는 경우)
    q = re.sub(r'(?<!제)([1-4])학생회관', lambda m: f"제{m.group(1)}학생회관", q)
    # "N학" 패턴: 숫자+학 (제N학생회관으로 확장), 단 이미 "제"가 앞에 있으면 스킵
    q = re.sub(r'(?<![제\d])([1-4])학(?=\s|$|[에서의뭐밥먹알이])', lambda m: f"제{m.group(1)}학생회관", q)
    # "중도" → "중앙도서관" (앞뒤에 한글 없는 경우)
    q = re.sub(r'(?<![가-힣])중도(?![서관가-힣])', '중앙도서관', q)

    # 2단계: 단순 문자열 치환
    q_padded = q + " "
    for abbr, full in _ABBREVIATION_MAP:
        q_padded = q_padded.replace(abbr, full)
    q = q_padded.strip()

    return q

